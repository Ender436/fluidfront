"""Generate FluidX3D v3.8 `setup.cpp` and `defines.hpp` from a CaseSpec.

The app drives the engine exclusively through these two generated files
(plus invoking the compiled binary) — the solver core is never patched.

Conventions (match FluidX3D's own aero examples):
- flow direction is +y; domain is (width nx, length ny, height nz)
- inflow/outflow/free-stream faces use TYPE_E equilibrium boundaries
- the model body is flagged TYPE_S|TYPE_X (TYPE_X = force-measurement mark)
- forces are measured with lbm.object_force() and written to forces.csv
- snapshots are binary VTK (SI units) written by the engine's own writers

Implementation note: the C++ is assembled from a template using @@TOKEN@@
substitution (never f-strings), so C++ braces need no escaping.
"""

from __future__ import annotations

from .schema import CaseSpec

# ---------------------------------------------------------------------------
# defines.hpp toggling


def _toggle_define(text: str, name: str, on: bool) -> str:
    """Flip `#define NAME` / `//#define NAME` lines in defines.hpp."""
    out = []
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith(f"//#define {name} ") and on:
            line = line.replace(f"//#define {name} ", f"#define {name} ", 1)
        elif line.lstrip().startswith(f"#define {name} ") and not on:
            line = line.replace(f"#define {name} ", f"//#define {name} ", 1)
        out.append(line)
    return "".join(out)


def generate_defines(spec: CaseSpec, base_text: str) -> str:
    text = base_text
    for name in ("D2Q9", "D3Q15", "D3Q19", "D3Q27"):
        want = name.lower() == spec.velocity_set
        text = _toggle_define(text, name, want)
    text = _toggle_define(text, "SRT", True)
    text = _toggle_define(text, "TRT", False)
    text = _toggle_define(text, "FP16S", spec.precision == "fp16s")
    text = _toggle_define(text, "FP16C", spec.precision == "fp16c")
    text = _toggle_define(text, "BENCHMARK", False)  # never the benchmark!
    tunnel = spec.flow.get("mode") != "volume_force"
    text = _toggle_define(text, "VOLUME_FORCE", not tunnel)
    text = _toggle_define(text, "FORCE_FIELD", True)  # forces.csv always written
    text = _toggle_define(text, "EQUILIBRIUM_BOUNDARIES", tunnel)
    text = _toggle_define(text, "SUBGRID", spec.subgrid)
    for name in ("MOVING_BOUNDARIES", "SURFACE", "TEMPERATURE", "PARTICLES",
                 "INTERACTIVE_GRAPHICS", "INTERACTIVE_GRAPHICS_ASCII", "GRAPHICS"):
        text = _toggle_define(text, name, False)
    return text


# ---------------------------------------------------------------------------
# setup.cpp template

TEMPLATE = r"""// GENERATED by fluidfront for case @@NAME@@ -- do not edit by hand.
// source of truth: @@CASE_JSON@@
#include "setup.hpp"

void main_setup() {
    // ############## resolved parameters (computed by fluidfront) ##########
    const uint NX = @@NX@@u, NY = @@NY@@u, NZ = @@NZ@@u;
    const float NU = @@NU@@;      // kinematic viscosity [LU]; tau = @@TAU@@
    const float U0 = @@U0@@;      // reference velocity [LU]
    const ulong T_MAX = @@TMAX@@ull;
    const ulong DT_FORCE = @@DTF@@ull;
    const ulong DT_SNAP = @@DTS@@ull;
    const string OUT = "@@OUT@@";
    println("fluidfront: Re_lu = @@RELU@@, tau = @@TAU@@, cells = @@NCELLS@@ M");

    LBM lbm(@@CTOR@@);
@@UNITS@@
@@GEO_PRE@@
    // ############## geometry ##############
    {
        parallel_for(lbm.get_N(), [&](ulong n) { uint x=0u, y=0u, z=0u; lbm.coordinates(n, x, y, z);
@@GEO@@
@@BOUNDARY@@
        });
    }

    // ############## run + measurement loop ##############
    lbm.run(0ull, T_MAX); // initialize (uploads host flags/u to device)
    lbm.flags.write_device_to_vtk(OUT); // geometry snapshot (once; engine appends "flags-<t>.vtk")

    // projected body area normal to flow: count TYPE_X voxel columns
    double AREA = 0.0; {
        std::vector<char> hit((size_t)NX * (size_t)NZ, 0);
        parallel_for(lbm.get_N(), [&](ulong n) { if(lbm.flags[n] & TYPE_X) {
            uint x=0u, y=0u, z=0u; lbm.coordinates(n, x, y, z); hit[(size_t)z*(size_t)NX+(size_t)x] = 1;
        } });
        for(const char c : hit) AREA += (double)c;
        if(AREA <= 0.0) AREA = 1.0; // no marked body: keep coefficients at 0
    }
    println("fluidfront: projected area = " + to_string((float)AREA, 1u) + " LU^2");

    std::ofstream forces(OUT + "forces.csv");
    forces << "# t,fx,fy,fz,cd,cl\n";
    const double QDYN_A = 0.5 * (double)U0 * (double)U0 * AREA; // rho = 1 [LU]

    while(lbm.get_t() < T_MAX) { // main simulation loop
        const ulong dt = (T_MAX - lbm.get_t()) < DT_FORCE ? (T_MAX - lbm.get_t()) : DT_FORCE;
        lbm.run(dt, T_MAX);
        const float3 F = lbm.object_force(TYPE_S|TYPE_X);
        double cd = 0.0, cl = 0.0;
        if(QDYN_A > 0.0) { cd = F.y / QDYN_A; cl = F.x / QDYN_A; }
        forces << lbm.get_t() << "," << F.x << "," << F.y << "," << F.z << ","
               << cd << "," << cl << "\n" << std::flush;
@@SNAPSHOT@@
    }
    println("fluidfront: done at t = " + to_string(lbm.get_t()) + " steps");
}
"""

SNAPSHOT_BLOCK = r"""        if(lbm.get_t() % DT_SNAP == 0ull || lbm.get_t() == T_MAX) { // incl. final frame
@@RHO@@            lbm.u.write_device_to_vtk(OUT);
            double u_max = 0.0;
            parallel_for(lbm.get_N(), [&](ulong n) { u_max = fmax(u_max, (double)sqrt(sq(lbm.u.x[n]) + sq(lbm.u.y[n]) + sq(lbm.u.z[n]))); });
            println("fluidfront: snapshot t = " + to_string(lbm.get_t()) + ", u_max = " + to_string((float)u_max, 4u) + " LU");
        }
"""

GEO_SNIPPETS = {
    "cylinder": """        if(cylinder(x, y, z, float3(@@CX@@, @@CY@@, @@CZ@@), float3(0u, 0u, (uint)NZ), @@R@@)) {
            lbm.flags[n] = TYPE_S|TYPE_X;
        } else {
            lbm.u.y[n] = U0;
        }""",
    "sphere": """        if(sphere(x, y, z, float3(@@CX@@, @@CY@@, @@CZ@@), @@R@@)) {
            lbm.flags[n] = TYPE_S|TYPE_X;
        } else {
            lbm.u.y[n] = U0;
        }""",
    "cuboid": """        if(cuboid(x, y, z, float3(@@CX@@, @@CY@@, @@CZ@@), float3(@@LX@@, @@LY@@, @@LZ@@))) {
            lbm.flags[n] = TYPE_S|TYPE_X;
        } else {
            lbm.u.y[n] = U0;
        }""",
    "pipe": """        if(!cylinder(x, y, z, lbm.center(), float3(0u, (uint)NY, 0u), @@R@@)) {
            lbm.flags[n] = TYPE_S;
        }""",
    "none": """        lbm.u.y[n] = U0;""",
    "stl": """        if(lbm.flags[n] != TYPE_S) {
            lbm.u.y[n] = U0;
        }""",
}

STL_PRE_BLOCK = r"""    { // STL model, euler XYZ degrees (@@ROT@@)
        const float3x3 rot = float3x3(float3(1, 0, 0), radians(@@RX@@)) * float3x3(float3(0, 1, 0), radians(@@RY@@)) * float3x3(float3(0, 0, 1), radians(@@RZ@@));
        lbm.voxelize_stl("@@STL@@", float3(@@CX@@, @@CY@@, @@CZ@@), rot, @@SIZE@@, TYPE_S|TYPE_X);
        lbm.flags.read_from_device();
    }"""


def _f(v) -> str:
    """C++ float literal: Python repr always carries '.' or 'e' (32.0, 3.125e-05)."""
    return repr(float(v)) + "f"


def _center_lu(spec: CaseSpec) -> tuple[float, float, float]:
    c = spec.geometry.get("center", "auto")
    if c in ("auto", None):
        fx, fy, fz = 0.5, 0.25, 0.5
    else:
        fx, fy, fz = (float(v) for v in c)
    return fx * spec.nx, fy * spec.ny, fz * spec.nz


def _sub(text: str, mapping: dict[str, str]) -> str:
    for k, v in mapping.items():
        text = text.replace(k, v)
    return text


def generate_setup(spec: CaseSpec) -> str:
    d = spec.derived
    kind = str(spec.geometry["kind"]).lower()
    cx, cy, cz = _center_lu(spec)
    size = float(spec.geometry["size_lu"])
    r = 0.5 * size

    # --- LBM constructor + SI unit mapping -------------------------------
    if spec.flow.get("mode") == "volume_force":
        umax = spec.flow.get("u_max_lu", 0.1)
        ctor = (f"NX, NY, NZ, 1u, 1u, 1u, NU, 0.0f, "
                f"units.f_from_u_Poiseuille_3D({_f(umax)}, 1.0f, NU, {_f(r)}), 0.0f")
        units_line = ""
    else:
        ctor = "NX, NY, NZ, 1u, 1u, 1u, NU"
        units_line = ('    units.set_m_kg_s(%s, U0, 1.0f, %s, %s, %s); // SI units for VTK output\n'
                      % (_f(d.size_lu), _f(float(spec.flow["length_si"])),
                         _f(float(spec.flow["u_si"])), _f(d.rho_si)))

    # --- geometry ---------------------------------------------------------
    geo_pre = ""
    if kind == "stl":
        rot = [float(v) for v in spec.geometry.get("rotation_deg", [90.0, 0.0, 0.0])]
        geo_pre = _sub(STL_PRE_BLOCK, {
            "@@ROT@@": str(rot), "@@RX@@": _f(rot[0]), "@@RY@@": _f(rot[1]),
            "@@RZ@@": _f(rot[2]), "@@STL@@": spec.geometry["path_abs"].replace("\\", "/"),
            "@@CX@@": _f(cx), "@@CY@@": _f(cy), "@@CZ@@": _f(cz), "@@SIZE@@": _f(size),
        })

    extents = spec.geometry.get("extents") or [size, size, size]
    geo = _sub(GEO_SNIPPETS[kind], {
        "@@CX@@": _f(cx), "@@CY@@": _f(cy), "@@CZ@@": _f(cz), "@@R@@": _f(r),
        "@@LX@@": _f(extents[0]), "@@LY@@": _f(extents[1]), "@@LZ@@": _f(extents[2]),
    })

    if spec.flow.get("mode") == "volume_force":
        boundary = "        // fully periodic pressure-driven channel (validation)"
    else:
        zface = "" if spec.nz == 1 else "||z==NZ-1u"
        ground = "\n        if(z==0u) { lbm.flags[n] = TYPE_S; }" if spec.geometry.get("ground") else ""
        boundary = (f"        if(x==0u||x==NX-1u||y==0u||y==NY-1u{zface}) {{ lbm.flags[n] = TYPE_E; }}{ground}")

    # --- snapshots ----------------------------------------------------------
    rho_line = '            lbm.rho.write_device_to_vtk(OUT);\n' if spec.run.get("write_rho") else ""
    snapshot = SNAPSHOT_BLOCK.replace("@@RHO@@", rho_line)

    force_every = int(spec.run.get("force_every", 25))
    snap_every = int(spec.run.get("snapshot_every", 0)) or 5 * force_every

    out = _sub(TEMPLATE, {
        "@@NAME@@": repr(spec.name),
        "@@CASE_JSON@@": str(spec.case_dir / "case.json"),
        "@@NX@@": str(spec.nx), "@@NY@@": str(spec.ny), "@@NZ@@": str(spec.nz),
        "@@NU@@": _f(d.nu_lu), "@@TAU@@": f"{d.tau:.6f}",
        "@@U0@@": _f(d.u_lu),
        "@@TMAX@@": str(int(spec.run["t_steps"])),
        "@@DTF@@": str(force_every), "@@DTS@@": str(snap_every),
        "@@OUT@@": str(spec.output_dir).replace("\\", "/") + "/",
        "@@RELU@@": f"{d.re_lu:.6g}",
        "@@NCELLS@@": f"{spec.nx * spec.ny * spec.nz / 1e6:.3f}",
        "@@CTOR@@": ctor,
        "@@UNITS@@": units_line,
        "@@GEO_PRE@@": geo_pre,
        "@@GEO@@": geo,
        "@@BOUNDARY@@": boundary,
        "@@SNAPSHOT@@": snapshot,
    })
    return out
